#!/usr/bin/env bash
# Лабораторная 1.1. Рисование инициалов «МАЭ» (Микулич Алексей Эдуардович)
# в окне TurtleSim методом тартл-графики.
#
# Требования задания: кириллица, верхний регистр, три цвета, разная ширина.
#   М - красная,  перо 3 px
#   А - жёлтая,   перо 6 px
#   Э - белая,    перо 9 px, скруглённая часть - дуга (линейная + угловая скорость)
#
# Используемые сервисы и темы turtlesim:
#   /clear                        - очистить окно
#   /turtle1/set_pen              - цвет (r g b), ширина пера, off (1 - перо поднято)
#   /turtle1/teleport_absolute    - перемещение в точку (x, y, theta);
#                                   при опущенном пере рисует прямой отрезок
#   /turtle1/cmd_vel              - линейная и угловая скорость; turtlesim исполняет
#                                   команду 1 с, rostopic pub -1 завершается через ~3 с
#
# Окно TurtleSim: 11.09 x 11.09 единиц, (0, 0) - левый нижний угол.
# Запуск: rosrun lab1_1_turtle draw_initials.sh  (turtlesim_node должен быть запущен)

set -e

PI=3.14159265

# ждём, пока turtlesim поднимет свои сервисы
until rosservice list 2>/dev/null | grep -q "/turtle1/teleport_absolute"; do
  echo "waiting for turtlesim..."
  sleep 1
done

pen() {            # pen R G B WIDTH OFF
  rosservice call /turtle1/set_pen "$1" "$2" "$3" "$4" "$5" > /dev/null
}

go() {             # go X Y [THETA] - прямой отрезок (или перенос, если перо поднято)
  rosservice call /turtle1/teleport_absolute "$1" "$2" "${3:-0.0}" > /dev/null
}

move() {           # move LINEAR ANGULAR - движение в течение 1 с
  rostopic pub -1 /turtle1/cmd_vel geometry_msgs/Twist \
    "{linear: {x: $1, y: 0.0, z: 0.0}, angular: {x: 0.0, y: 0.0, z: $2}}" > /dev/null
}

pen_up() { pen 0 0 0 1 1; }

# ---------------------------------------------------------------- подготовка
pen_up
go 0.8 3.5
rosservice call /clear > /dev/null

# ---------------------------------------------------------------- М
# четыре отрезка: левая стойка, две диагонали, правая стойка
pen 255 0 0 3 0
go 0.8 7.5
go 2.0 5.3
go 3.2 7.5
go 3.2 3.5
pen_up

# ---------------------------------------------------------------- А
# две наклонные стороны и перекладина
go 3.9 3.5
pen 255 230 0 6 0
go 5.1 7.5
go 6.3 3.5
pen_up
go 4.35 5.0
pen 255 230 0 6 0
go 5.85 5.0
pen_up

# ---------------------------------------------------------------- Э
# верхний «хвост», полуокружность радиуса R = 2 по часовой стрелке,
# нижний «хвост» и средняя перекладина.
# Полуокружность за 1 с: угловая скорость w = -pi рад/с,
# линейная скорость v = |w| * R = 2 * pi.
go 7.0 7.5 0.0
pen 255 255 255 9 0
go 8.0 7.5 0.0
move 6.28318531 "-$PI"
go 8.0 3.5 $PI          # компенсация погрешности интегрирования дуги
go 7.0 3.5 $PI
pen_up
go 7.6 5.5 0.0
pen 255 255 255 9 0
go 10.0 5.5 0.0
pen_up

# убираем черепашку в угол, чтобы она не закрывала буквы
go 10.3 1.0 1.5708
echo "done: МАЭ"
